<?php
// Regenerate SWUSim/Custom/BotOpponentStyles.php — the bot's META KNOWLEDGE of what a leader + base combination usually plays
// (owner 2026-10-11: "it should be based on the leader/base combo"). The opponent's decklist is hidden, so the bot may not classify
// it; its leader and base are public, and what that pairing typically is in the meta is what a human player knows too ("resource
// HSD unless my opponent is typically known to have a go-wide space strategy"). Replaces the hand-kept SWU_BOT_AGGRO_LEADERS list
// behind proposal 'stylemap' (BotResourcing.php).
// Run after a classifier change, an owner relabel, or a new meta set — the map is DERIVED, never hand-edited:
//   docker exec -w /var/www/html/TCGEngine otmtcge-swusim-web-server-1 php -d xdebug.mode=off SWUSim/DevTools/regen-opponent-styles.php
// Sources, every list weighted 1:
//   - the owner-labelled curated fixture groups below ('# DeckStyle:' — what the deck IS — over '# Style:', how the bot pilots it);
//   - every real list in SWUSim/Tests/BotFixtures/meta-baselines/*/fixtures.tar.gz, labelled by the curated fixture of its EXACT
//     archetype (SWUBotFixtureFileName) when one exists, else by the deck-style classifier (SWUBotDeckStyle: label overlap, then shape).
//     The baked '# Style:' header of a tournament list is NOT trusted: re-deriving it here is what lets a classifier fix reach the map.
chdir(dirname(__DIR__, 2));
require_once './SWUSim/GeneratedCode/GeneratedCardDictionaries.php';
require_once './SWUSim/Rl/CardTags.php';
require_once './SWUSim/Custom/BotDeckStyle.php';

const SWU_OSM_STYLES = ['hyperaggro' => 0, 'softaggro' => 1, 'midrange' => 2, 'softcontrol' => 3, 'hardcontrol' => 4];
const SWU_OSM_CURATED = ['ash-meta-2026-09', 'hmw-meta-2026-09', 'force-fam-HMW-predictions'];
$OUT = './SWUSim/Custom/BotOpponentStyles.php';

$styleOf = function (string $text): ?string {
    preg_match('/^# DeckStyle:\s*(\S+)/m', $text, $dm); preg_match('/^# Style:\s*(\S+)/m', $text, $m);
    $s = strtolower(strval($dm[1] ?? $m[1] ?? ''));
    return isset(SWU_OSM_STYLES[$s]) ? $s : null;
};
// Every list: [leader, base, style, source].
$lists = []; $curatedByName = [];
foreach (SWU_OSM_CURATED as $g) {
    foreach (glob("./SWUSim/Tests/BotFixtures/$g/*.txt") ?: [] as $path) {
        $text = (string)file_get_contents($path); $style = $styleOf($text); $deck = SWUBotDeckFromFixtureText($text);
        if ($style === null || $deck['leader'] === '' || $deck['base'] === '') { fwrite(STDERR, "skip curated " . basename($path) . " (no style/leader/base)\n"); continue; }
        $curatedByName[basename($path, '.txt')] ??= $style;   // first group wins (the order above)
        $lists[] = [$deck['leader'], $deck['base'], $style, "curated:$g"];
    }
}
$tmp = sys_get_temp_dir() . '/swu-osm-' . getmypid();
foreach (glob('./SWUSim/Tests/BotFixtures/meta-baselines/*/fixtures.tar.gz') ?: [] as $tar) {
    $dir = "$tmp/" . basename(dirname($tar)); @mkdir($dir, 0777, true);
    exec('tar xzf ' . escapeshellarg($tar) . ' -C ' . escapeshellarg($dir), $o, $rc);
    if ($rc !== 0) { fwrite(STDERR, "REFUSED: cannot unpack $tar\n"); exit(1); }
    foreach (glob("$dir/fx/*.txt") ?: [] as $path) {
        $deck = SWUBotDeckFromFixtureText((string)file_get_contents($path));
        if ($deck['leader'] === '' || $deck['base'] === '' || empty($deck['cards'])) continue;
        $name = SWUBotFixtureFileName($deck['leader'], $deck['base'], $deck['cards']);
        if (isset($curatedByName[$name])) { $lists[] = [$deck['leader'], $deck['base'], $curatedByName[$name], 'fixture']; continue; }
        $r = SWUBotDeckStyle($deck);
        if (!isset(SWU_OSM_STYLES[strval($r['style'] ?? '')])) continue;
        $lists[] = [$deck['leader'], $deck['base'], strval($r['style']), strval($r['source'])];
    }
}
exec('rm -rf ' . escapeshellarg($tmp));

// Three keys per list, most to least specific — the runtime falls back in this order (as SWU_BOT_FLAVOURS does).
$agg = []; $src = [];
foreach ($lists as [$L, $B, $style, $source]) {
    $aspect = explode(',', strval(CardAspect($B) ?? ''))[0];
    foreach (["$L|$B", "$L|aspect:$aspect", "$L|*"] as $k) $agg[$k][$style] = ($agg[$k][$style] ?? 0) + 1;
    $src[$source] = ($src[$source] ?? 0) + 1;
}
ksort($agg);
$rows = [];
foreach ($agg as $k => $counts) {
    $n = array_sum($counts); $sum = 0;
    foreach ($counts as $s => $c) $sum += SWU_OSM_STYLES[$s] * $c;
    arsort($counts);
    $rows[] = sprintf("    %s => ['rank' => %.2f, 'n' => %d, 'styles' => %s],", var_export($k, true), $sum / $n, $n,
        str_replace(["\n", '  ', 'array (', ',)'], ['', '', '[', ']'], var_export($counts, true)));
}
$php = "<?php\n// GENERATED by SWUSim/DevTools/regen-opponent-styles.php — do not hand-edit; re-run the generator.\n"
     . "// What each leader + base usually plays in the meta (rank 0 hyperaggro … 4 hardcontrol, the mean over n real lists).\n"
     . "// Keys: 'LEADER|BASE', 'LEADER|aspect:<base aspect>', 'LEADER|*'. Sources: " . json_encode($src) . ".\n"
     . "const SWU_BOT_OPPONENT_STYLES = [\n" . implode("\n", $rows) . "\n];\n";
file_put_contents($OUT, $php);
echo 'lists: ' . count($lists) . ' ' . json_encode($src) . "\nkeys: " . count($agg) . " -> $OUT\n";
