<?php
// The final eight from the original unreferenced-card audit.
gaScenario('remaining-numinous-monk-granted-spell')
    ->deckTemplate('quiet','Dungeon Guide')
    ->seed('myField','Numinous Monk')->seed('myField','Bauble of Abundance')
    ->action(1,10001,'myField-2!CustomInput!Activate:1')->answer(1,'theirField-0')->passBoth()
    ->expectDamage('p2Field-0',1)->expectProperty('p1Field-2','Status','1')
    ->expectDqEmpty()->tested('Numinous Monk')->covers(['grant','rest','damage'],'Regalia pays REST for the granted Spell and deals one damage.')->register();
gaScenario('remaining-orb-seals-two-in-one-banishment')
    ->deckTemplate('quiet','Dungeon Guide')->seed('myField','Orb of Sealing')
    ->seed('myBanish','Dungeon Guide')->seed('myBanish','Dungeon Guide')
    ->action(1,10001,'myField-1!CustomInput!Activate:0')
    ->answer(1,'myBanish-0')->answer(1,'myBanish-1')->passBoth()
    ->expectProperty('p1Banish-0','Counters','{"seal":1,"_sealFaceDown":1}')
    ->expectProperty('p1Banish-1','Counters','{"seal":1,"_sealFaceDown":1}')
    ->expectProperty('p1Field-1','Status','1')->expectDqEmpty()->tested('Orb of Sealing')
    ->covers(['rest','seal','face-down'],'Seal two cards in one banishment and pay REST.')->register();
gaScenario('remaining-soul-materializes-opponents-regalia')
    ->deckTemplate('quiet','Dungeon Guide')->readyFor('Materialize the Soul')
    ->champion(cardName:'Merlin, Kingslayer')->champion(cardName:'Diana, Moonpiercer',player:2)
    ->seed('myMaterial','Bauble of Abundance',player:2)->seed('myHand','Materialize the Soul')
    ->castSpell('Materialize the Soul',pay:6)->answer(1,'theirMaterial-4')->passBoth()
    ->expectCardExists('myField','Bauble of Abundance')->expectProperty('p1Field-1','Owner','2')
    ->expectProperty('p1Field-0','Counters','{"soulClasses":["RANGER"]}')
    ->expectDqEmpty()->tested('Materialize the Soul')->covers(['materialize','class','ownership'],'Gain opposing classes and materialize opponent regalia under your control.')->register();
gaScenario('remaining-regulus-hand-costs-and-permission')
    ->deckTemplate('quiet','Dungeon Guide')->champion(cardName:'Mordred, Fated Luminary')
    ->seed('myHand','Regulus Blitz')->action(1,10001,'myHand-7!CustomInput!Activate:0')
    ->pay(2)->passBoth()->expectCardExists('myGraveyard','Regulus Blitz')
    ->expectZoneCount('myMemory',2)->expectGlobalEffect(1,'REGULUS_NEXT_ATTACK')->expectDqEmpty()
    ->tested('Regulus Blitz')->covers(['hand-ability','discard','reserve'],'Discard Regulus and pay two for the next attack permission.')->register();
gaScenario('remaining-tristan-transfers-attack-to-shadow')
    ->deckTemplate('quiet','Dungeon Guide')->champion(cardName:'Tristan, Ascendant Shadow')
    ->globalEffect('TRISTAN_ASCENDANT_ATTACKS')->seed('myField','Ominous Shadow')
    ->seed('myHand','Reckless Slash')->reachTurnThree()
    ->play('Reckless Slash')->pay(2)->answer(1,'theirField-0')
    ->answer(1,'myField-1')->answer(1,'theirField-0')->passBoth()
    ->expectDamage('p2Field-0',7)->expectProperty('p1Field-1','Status','1')
    ->expectZoneCount('myIntent',0)->expectZoneCount('myGraveyard',1)
    ->expectCardExists('myGraveyard','Reckless Slash')->expectDqEmpty()->tested('Tristan, Ascendant Shadow')
    ->covers(['on-hit','attack','physical-card'],'Transfer the original attack card into a Shadow attack, then put it into the graveyard once.')->register();
gaScenario('remaining-lightweaver-shares-reveals-and-sacrifices')
    ->deckTemplate('quiet','Dungeon Guide')->champion(cardName:'Zander, Blinding Steel',damage:15)
    ->seed('myMemory','Luxem Sight')->seed('myMemory','Luxem Sight')
    ->seed('myField',"Lightweaver's Infinite Shaping")->observe()->endTurn()
    ->expectDamage('p1Field-0',3)->expectCardExists('myGraveyard',"Lightweaver's Infinite Shaping")
    ->expectZoneCount('myField',1)->expectDqEmpty()->tested("Lightweaver's Infinite Shaping")
    ->covers(['enter','reveal','copy','sacrifice'],'Both revealed cards have both recover abilities; Shaping sacrifices at end phase.')->register();
gaScenario('remaining-lightweaver-copied-bonuses-use-recipient')
    ->deckTemplate('quiet','Dungeon Guide')->champion(cardName:'Zander, Blinding Steel',damage:15)
    ->seed('myMemory','Luxem Sight')->seed('myMemory','Elucidate Plans')
    ->seed('myField',"Lightweaver's Infinite Shaping")
    ->answer(1,'0')->answer(1,'0')->answer(1,'0')
    ->expectDamage('p1Field-0',9)->expectProperty('p1Field-0','Counters','{"preparation":1}')
    ->expectDqEmpty()->tested("Lightweaver's Infinite Shaping")
    ->covers(['reveal','copy','class-bonus','trigger-order'],'Choose reveal trigger order; the Cleric card cannot enable its copied Assassin class bonus.')->register();
gaScenario('remaining-soul-pays-opponents-regalia-memory-cost')
    ->deckTemplate('quiet','Dungeon Guide')->readyFor('Materialize the Soul')->champion(cardName:'Merlin, Kingslayer')
    ->seed('myMaterial','Bauble of Mending',player:2)->seed('myHand','Materialize the Soul')
    ->castSpell('Materialize the Soul',pay:6)->answer(1,'theirMaterial-4')->passBoth()
    ->expectCardExists('myField','Bauble of Mending')->expectProperty('p1Field-1','Owner','2')
    ->expectZoneCount('myMemory',5)->expectZoneCount('myBanish',1)->expectDqEmpty()->tested('Materialize the Soul')
    ->covers(['materialize','memory-cost','ownership'],'Materializing from the opponent deck pays the normal one-memory cost.')->register();
