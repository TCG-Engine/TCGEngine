<?php
// Furnace Drone pays three eligible graveyard cards before reserve and responses.
gaScenario('furnace-elements-dual')
    ->deckTemplate('quiet', 'Dungeon Guide')
    ->seed('myGraveyard', 'Scorched Conquest', player: 1)
    ->seed('myGraveyard', 'Scorched Conquest', player: 1)
    ->seed('myGraveyard', 'Scorched Conquest', player: 1)
    ->seed('myGraveyard', 'Eminent Lethargy', player: 1)->seed('myGraveyard', 'Dungeon Guide', player: 1)
    ->seed('myHand', 'Furnace Drone', player: 1)
    ->play('Furnace Drone', player: 1)
    ->rejects(1, 'myGraveyard-3', 'Dual Water is not Fire or Automaton')
    ->rejects(1, 'myGraveyard-4', 'Ordinary Norm non-Automaton is excluded')
    ->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')
    ->expectZoneCount('myBanish', 3, 1, 'All three cards are banished before reserve payment', step: 6)
    ->expectZoneCount('myMemory', 0, 1, 'Reserve payment follows the mandatory banishes', step: 6)
    ->pay(3, player: 1)
    ->expectZoneCount('myMemory', 3, 1, 'Printed reserve is still paid')
    ->expectZoneCount('myBanish', 3, 1, 'Exactly three eligible cards were paid')
    ->expectZoneCount('myGraveyard', 2, 1, 'Ineligible cards remain in the graveyard')
    ->expectCardExists('myField', 'Furnace Drone', 'The paid activation resolves', viewer: 1)
    ->tested('Furnace Drone')->covers(['cost', 'element'], 'Banish three Fire element and/or Automaton cards as an additional activation cost.')->register();

