gaScenario('furnace-elements-insufficient')
    ->deckTemplate('quiet', 'Dungeon Guide')
    ->seed('myGraveyard', 'Scorched Conquest')->seed('myGraveyard', 'Red Slime')
    ->seed('myGraveyard', 'Eminent Lethargy')->seed('myHand', 'Furnace Drone')
