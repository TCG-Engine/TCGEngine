gaScenario('senaris-cardistry-adds-three-damage-to-the-next-suited-spell-sources')
    ->standardDeck('Senaris, Six of Diamonds')
    ->readyFor('Senaris, Six of Diamonds')
    ->seed('myField', 'Senaris, Six of Diamonds')
    ->readyFor('Bolt of Diamonds')
    ->seed('myHand', 'Bolt of Diamonds')
    ->action(1, 10001, 'myField-1!CustomInput!Activate:0')->pay(5)->passBoth()
    ->expectGlobalEffect(1, 'EIpkYYSP3s', 'Three Suited Spell damage boosts are pending', 3, 8)
    ->expectProperty('p1Field-1', 'Counters', '{"cardistry_used":1}', 'The once-only marker is set', 8)
    ->action(1, 10002, 'myHand-2!FSM!')->pay(2)->answer(1, 'theirField-0')->passBoth()
    ->expectDamage('p2Field-0', 4, 'Bolt of Diamonds deals 1 + 3 damage')
    ->expectGlobalEffect(1, 'EIpkYYSP3s', 'One of the three boosts was used', 2)
    ->tested('Senaris, Six of Diamonds')
    ->covers(['cardistry', 'damage', 'once-per-game'], '***Cardistry*** — (6): The next three times a Suited Spell source you control would deal damage this turn, it deals that much plus 3 damage instead.')
    ->register();

