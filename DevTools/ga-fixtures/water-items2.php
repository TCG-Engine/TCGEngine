gaScenario('dian-wei-class-bonus-on-enter-mills-one-card-per-human-ally')
    ->deck("# Material\n1 Spirit of Water\n# Main\n14 Dungeon Guide")
    ->readyFor('Dian Wei, Valorant Fury', classBonus: true)
    ->seed('myField', 'Dynasty Chancellor')->seed('myField', 'Dynasty Chancellor')
    ->seed('myField', 'Dian Wei, Valorant Fury')
    ->observe()
    ->expectZoneCount('myGraveyard', 3, 1, 'Three Human allies (two Chancellors and Dian Wei): three cards milled')
    ->expectZoneCount('myDeck', 4, 1, 'The deck is three cards shorter (7 - 3)')
    ->tested('Dian Wei, Valorant Fury')
    ->covers(['on-enter', 'class-bonus', 'mill', 'human'], '[Class Bonus] **On Enter**: For each Human ally you control, put the top card of your deck into your graveyard.')
    ->register();

