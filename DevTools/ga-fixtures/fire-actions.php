gaScenario('tyrannical-denigration-class-bonus-kindle-seven-pays-from-the-graveyard')
    ->standardDeck('Tyrannical Denigration')
    ->readyFor('Tyrannical Denigration', classBonus: true)
    ->seed('myGraveyard', 'Red Slime')->seed('myGraveyard', 'Red Slime')->seed('myGraveyard', 'Red Slime')
    ->seed('myGraveyard', 'Red Slime')->seed('myGraveyard', 'Red Slime')->seed('myGraveyard', 'Red Slime')
    ->seed('myGraveyard', 'Red Slime')
    ->seed('myHand', 'Tyrannical Denigration')
    ->reachTurnThree()
    ->playSlot(7)
    ->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')
    ->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')->answer(1, 'myGraveyard-0')
    ->target('theirField-0')
    ->expectZoneCount('myBanish', 7, 1, 'Kindle 7: seven fire cards were banished from the graveyard, each paying 1')
    ->expectZoneCount('myHand', 8, 1, 'The whole cost was paid from the graveyard: no hand cards went to memory')
    ->expectDamage('p2Field-0', 8, '[Class Bonus] 4 POWER + 4 = 8 damage')
    ->tested('Tyrannical Denigration')
    ->covers(['kindle', 'class-bonus', 'combat'], '**Kindle 7**', '[Class Bonus] CARDNAME gets +4 [POWER] and can\'t be retaliated.')
    ->register();

