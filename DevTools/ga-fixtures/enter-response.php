<?php
// A real activation and pending On Enter, rather than a seeded triggerless target.
gaScenario('enter-response-stifling-aethercharge-negates-broker')
    ->deckTemplate('quiet', 'Dungeon Guide')->readyFor('Blackmarket Broker')->readyFor('Stifling Aethercharge', player: 2)
    ->seed('myHand', 'Stifling Aethercharge', player: 2)
    ->seed('myHand', 'Blackmarket Broker')
    ->rawAction(['playerID' => 2, 'mode' => 10015, 'cardID' => '', 'inputText' => '{"version":1,"windows":{"ENTER_RESPONSE":false}}'])
    ->play('Blackmarket Broker')->pay(4)
    ->pass(2)
    ->answer(2, 'myHand-7')->pay(2, player: 2)->target('theirField-1', player: 2)
    ->expectProperty('p1Field-0', 'Counters', '[]', 'The negated On Enter never adds a preparation counter')
    ->expectCardExists('myField', 'Blackmarket Broker', 'Negating the trigger leaves the ally in play', viewer: 1)
    ->expectDqEmpty()
    ->expectZoneCount('EffectStack', 0, 1, 'All pending entries have settled')
    ->tested('Stifling Aethercharge')->covers(['negate', 'enter', 'response'], 'Negate all On Enter triggers from target ally.')->register();

gaScenario('enter-response-etui-declined-payment')
    ->deckTemplate('quiet', 'Dungeon Guide')->readyFor('Blackmarket Broker')
    ->champion(level: 2, player: 2)
    ->seed('myField', 'Frostbitten Etui', player: 2)
    ->seed('myHand', 'Blackmarket Broker')
    ->rawAction(['playerID' => 2, 'mode' => 10015, 'cardID' => '', 'inputText' => '{"version":1,"windows":{"ENTER_RESPONSE":false}}'])
    ->play('Blackmarket Broker')->pay(4)->pass(2)
    ->answer(2, 'myField-1@Activate-0@bdhjszsj2z')->target('theirField-1', player: 2)->answer(1, 'NO')
    ->expectProperty('p1Field-0', 'Counters', '[]', 'Declining payment lets Etui negate the pending trigger')
    ->expectCardExists('myBanish', 'Frostbitten Etui', 'Etui is banished to pay its activation', viewer: 2)
    ->expectCardExists('myField', 'Blackmarket Broker', 'The ally survives its trigger being negated')
    ->expectDqEmpty()
    ->expectZoneCount('EffectStack', 0, 1, 'All pending entries have settled')
    ->tested('Frostbitten Etui')->covers(['negate', 'enter', 'payment'], 'Negate all On Enter triggers from target opposing ally unless its controller pays three.')->register();

gaScenario('enter-response-etui-paid')
    ->deckTemplate('quiet', 'Dungeon Guide')->readyFor('Blackmarket Broker')
    ->champion(level: 2, player: 2)
    ->seed('myField', 'Frostbitten Etui', player: 2)
    ->seed('myHand', 'Blackmarket Broker')
    ->rawAction(['playerID' => 2, 'mode' => 10015, 'cardID' => '', 'inputText' => '{"version":1,"windows":{"ENTER_RESPONSE":false}}'])
    ->play('Blackmarket Broker')->pay(4)->pass(2)
    ->answer(2, 'myField-1@Activate-0@bdhjszsj2z')->target('theirField-1', player: 2)->answer(1, 'YES')->answer(1, 'myHand-0&myHand-1&myHand-2')
    ->expectProperty('p1Field-0', 'Counters', '{"preparation":1}', 'Paying three preserves the pending trigger')
    ->expectCardExists('myBanish', 'Frostbitten Etui', 'Etui is banished to pay its activation', viewer: 2)
    ->expectCardExists('myField', 'Blackmarket Broker', 'The ally survives its trigger being negated')
    ->expectZoneCount('myMemory', 7, 1, 'Four activation reserve plus three to prevent negation')
    ->expectDqEmpty()
    ->expectZoneCount('EffectStack', 0, 1, 'All pending entries have settled')
    ->tested('Frostbitten Etui')->covers(['negate', 'enter', 'payment'], 'Negate all On Enter triggers from target opposing ally unless its controller pays three.')->register();
