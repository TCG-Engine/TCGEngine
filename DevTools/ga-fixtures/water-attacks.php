gaScenario('floodborne-swing-class-bonus-deluge-three-gets-plus-four-power')
    ->standardDeck('Floodborne Swing')
    ->readyFor('Floodborne Swing', classBonus: true)
    ->seed('myGraveyard', 'Giant Tortoise')->seed('myGraveyard', 'Giant Tortoise')->seed('myGraveyard', 'Giant Tortoise')
    ->seed('myHand', 'Floodborne Swing')
    ->reachTurnThree()
    ->playSlot(7)->pay(2)->target('theirField-0')
    ->expectDamage('p2Field-0', 5, '[Class Bonus] Deluge 3: 1 + 4 = 5 damage')
    ->tested('Floodborne Swing')
    ->covers(['combat', 'deluge', 'class-bonus', 'stat-change'], '[Class Bonus]***Deluge 3 --*** As long as you have three or more water element cards in your graveyard, CARDNAME gets +4[POWER].')
    ->register();

