gaScenario('calculated-foresight-mills-two-and-banishing-a-floating-memory-card-gives-ranged-three')
    ->deckTemplate('quiet', 'Dungeon Guide')
    ->readyFor('Calculated Foresight')
    ->seed('myGraveyard', 'Brookside Scout')
    ->seed('myHand', 'Calculated Foresight')
    ->castSpell('Calculated Foresight', pay: 2)->answer(1, 'myGraveyard-0')
    ->expectProperty('p1Field-0', 'TurnEffects', '["vz4kc558yx-ACTION_ACTIVATED","RANGED_3"]', 'The champion gained ranged 3')
    ->expectCardExists('myBanish', 'Brookside Scout', 'The floating memory card was banished')
    ->tested('Calculated Foresight')
    ->covers(['mill', 'banish', 'floating-memory', 'ranged'], 'Put the top two cards of your deck into your graveyard. Then you may banish a card with **floating memory** from your graveyard. If you do, your champion gains **ranged 3** until end of turn.')
    ->register();

