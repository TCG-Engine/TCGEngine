gaScenario('sly-songstress-class-bonus-stealth-cannot-be-targeted-by-attacks')
    ->standardDeck('Sly Songstress')
    ->readyFor('Sly Songstress', classBonus: true)
    ->seed('myField', 'Sly Songstress')
    ->seed('myField', 'Dungeon Guide', player: 2, properties: ['Status' => 2])
