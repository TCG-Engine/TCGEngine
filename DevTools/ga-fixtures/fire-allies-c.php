gaScenario('two-of-hearts-cardistry-gets-plus-two-power')
    ->standardDeck('Two of Hearts')
    ->readyFor('Two of Hearts')
    ->seed('myField', 'Two of Hearts')
    ->action(1, 10001, 'myField-1!CustomInput!Activate:0')
    ->pay(1)
    ->tested('Two of Hearts')
    ->expectPower('p1Field-1', 3, 'Cardistry: +2 POWER (1 + 2 = 3); the cost was (2) minus one for the different-cost Suited object')
    ->expectZoneCount('myMemory', 1, 1, 'Exactly (1) was paid after the Cardistry reduction')
    ->covers(['activated-ability', 'cardistry', 'stat-change'], 'Cardistry -- (2): Two of Hearts gets +2 [POWER] until end of turn.')
    ->register();

gaScenario('three-of-hearts-cardistry-draws-then-discards')
    ->standardDeck('Three of Hearts')
