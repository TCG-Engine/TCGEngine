<?php
// Regenerates AppCore/SWU/PrintingRarities.php — the rarity each REPRINT has in a supplemental booster set (today IC27).
//
// Why: the card dictionary folds a reprint into its earliest printing (AppCore/SWU/Overrides.php CardIDOverride, e.g.
// IC27_154 → SHD_196 Grogu), so CardRarity() answers with the ORIGINAL rarity (Grogu: Special in SHD) — but a pack
// collates by the rarity printed in THAT set (Grogu: Uncommon in IC27). New cards of the set need nothing here: they are
// in the dictionary under their own ID with their own rarity.
//
// Source: the swu-db.com API (https://api.swu-db.com/cards/<set>), normal printings only. A reprint the API does not list
// yet is simply absent, and SWUSim/Limited/LimitedPacks.php leaves it out of packs until this is re-run — run it again
// as a preview set fills in, and once on its release day.
//   docker exec -w /var/www/html/TCGEngine otmtcge-swusim-web-server-1 php DevTools/swu-printing-rarities.php
chdir(__DIR__ . '/..');
require_once './AppCore/SWU/Overrides.php';
require_once './AppCore/SWU/BoosterSets.php';

$out = [];
foreach (array_keys(SWUSupplementalBoosterSets()) as $set) {
    $raw = @file_get_contents('https://api.swu-db.com/cards/' . strtolower($set) . '?format=json');
    $data = json_decode(strval($raw), true)['data'] ?? null;
    if (!is_array($data)) { fwrite(STDERR, "$set: the API gave no card list — nothing written\n"); exit(1); }
    $rows = [];
    foreach ($data as $c) {
        if (!ctype_digit(strval($c['Number'] ?? '')) || strval($c['VariantType'] ?? 'Normal') !== 'Normal') continue;
        $printing = sprintf('%s_%03d', $set, intval($c['Number']));
        $canonical = CardIDOverride($printing);
        if ($canonical === $printing) continue;   // a new card: the dictionary already has its rarity
        $rows[$printing] = strval($c['Rarity'] ?? '');
    }
    ksort($rows);
    $out[$set] = $rows;
    echo "$set: " . count($rows) . " reprints with a printed rarity\n";
}

$php = "<?php\n// GENERATED by DevTools/swu-printing-rarities.php from the swu-db.com API on " . gmdate('Y-m-d') . " — do not edit by hand.\n"
     . "// [set => [printing ID => the rarity printed in that set]] for REPRINTS only (CardIDOverride maps each to its card).\n"
     . "// A reprint missing here is not yet listed by the API and stays out of that set's packs.\n"
     . "return " . var_export($out, true) . ";\n";
file_put_contents('./AppCore/SWU/PrintingRarities.php', $php);
echo "wrote AppCore/SWU/PrintingRarities.php\n";
