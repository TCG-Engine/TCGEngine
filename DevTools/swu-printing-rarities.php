<?php
// Regenerates AppCore/SWU/PrintingRarities.php — the rarity each REPRINT has in a supplemental booster set (today IC27).
//
// Why: the card dictionary folds a reprint into its earliest printing (AppCore/SWU/Overrides.php CardIDOverride, e.g.
// IC27_154 → SHD_196 Grogu), so CardRarity() answers with the ORIGINAL rarity (Grogu: Special in SHD) — but a pack
// collates by the rarity printed in THAT set (Grogu: Uncommon in IC27). New cards of the set need nothing here: they are
// in the dictionary under their own ID with their own rarity.
//
// Source: the OFFICIAL FFG card data — SWUSim's generated dictionary, which zzCardCodeGenerator.php builds from the FFG
// API (admin.starwarsunlimited.com) and which carries every printing under its own ID with the rarity printed on it.
// Until 2026-11-08 this read the third-party swu-db.com API instead, which lagged: on IC27's official flip it still
// listed 40 of the 92 reprints (agreeing on all 40), so 52 sat out of packs. A set still on preview MOCKS has no reprint
// printings in the dictionary yet, so it gets no rows — reprints stay out of its packs until its official data lands.
// Re-run after every card regen that brings a supplemental set's official data (zzCardCodeGenerator rootName=SWUSim).
//   docker exec -w /var/www/html/TCGEngine otmtcge-swusim-web-server-1 php DevTools/swu-printing-rarities.php
chdir(__DIR__ . '/..');
require_once './SWUSim/GeneratedCode/GeneratedCardDictionaries.php';
require_once './AppCore/SWU/Overrides.php';
require_once './AppCore/SWU/BoosterSets.php';

$out = [];
foreach (array_keys(SWUSupplementalBoosterSets()) as $set) {
    $rows = [];
    foreach (GetAllCardIds() as $printing) {
        if (CardSet($printing) !== $set || !preg_match('/^' . preg_quote($set, '/') . '_\d{3}$/', $printing)) continue;
        if (CardIDOverride($printing) === $printing) continue;   // a new card: the dictionary already has its rarity
        $rarity = strval(CardRarity($printing) ?? '');
        if ($rarity === '') { fwrite(STDERR, "$printing has no rarity in the official data — left out\n"); continue; }
        $rows[$printing] = $rarity;
    }
    ksort($rows);
    $out[$set] = $rows;
    echo "$set: " . count($rows) . " reprints with a printed rarity\n";
}

$php = "<?php\n// GENERATED by DevTools/swu-printing-rarities.php from the official FFG card data on " . gmdate('Y-m-d') . " — do not edit by hand.\n"
     . "// [set => [printing ID => the rarity printed in that set]] for REPRINTS only (CardIDOverride maps each to its card).\n"
     . "// A reprint missing here has no official data yet and stays out of that set's packs.\n"
     . "return " . var_export($out, true) . ";\n";
file_put_contents('./AppCore/SWU/PrintingRarities.php', $php);
echo "wrote AppCore/SWU/PrintingRarities.php\n";
